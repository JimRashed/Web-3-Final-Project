"""Builds the Milestone 3 issue map for D05 (#66) from live GitHub data.

Writes docs/milestone3/traceability.json (machine-readable) and replaces the generated section of
docs/milestone3/requirements-traceability.md between the BEGIN/END markers. Requires the GitHub CLI (gh)
signed in with read access to the repository. Run from the repository root:

    python scripts/traceability/build-traceability.py
"""
import json
import os
import re
import shutil
import subprocess
import sys

REPO = "JimRashed/Web-3-Final-Project"
MILESTONE = "Milestone 3 — Layered Service Development"
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DOC = os.path.join(ROOT, "docs", "milestone3", "requirements-traceability.md")
EXPORT = os.path.join(ROOT, "docs", "milestone3", "traceability.json")
BEGIN, END = "<!-- BEGIN GENERATED ISSUE MAP -->", "<!-- END GENERATED ISSUE MAP -->"
# A PR counts for an issue when the issue is named in its title or on a Refs/Closes/Fixes/Implements line.
REFERENCE_LINE = re.compile(r"^\s*(refs|closes|fixes|implements|part of)\b[^\n]*", re.IGNORECASE | re.MULTILINE)


def gh(*args):
    exe = shutil.which("gh") or r"C:\Program Files\GitHub CLI\gh.exe"
    out = subprocess.run([exe, *args], capture_output=True, check=True)
    return json.loads(out.stdout.decode("utf-8"))


def stable_id(title):
    match = re.match(r"\[M3\]\[([A-Z0-9-]+)\]", title)
    return match.group(1) if match else "?"


def parent_of(body):
    match = re.search(r"\*\*Parent(?: feature)?:\*\*\s*#(\d+)", body or "")
    return int(match.group(1)) if match else None


def referenced(pr, numbers):
    text = pr["title"] + "\n" + "\n".join(m.group(0) for m in REFERENCE_LINE.finditer(pr.get("body") or ""))
    return {int(n) for n in re.findall(r"#(\d+)", text)} & numbers


def main():
    issues = gh("issue", "list", "--repo", REPO, "--milestone", MILESTONE, "--state", "all", "--limit", "200",
                "--json", "number,title,state,assignees,body,closedAt")
    prs = gh("pr", "list", "--repo", REPO, "--state", "all", "--limit", "300",
             "--json", "number,title,state,author,mergedAt,baseRefName,reviews,body")
    numbers = {issue["number"] for issue in issues}
    rows = []
    for issue in sorted(issues, key=lambda item: item["number"]):
        linked = [pr for pr in prs if issue["number"] in referenced(pr, numbers)]
        rows.append({
            "number": issue["number"],
            "id": stable_id(issue["title"]),
            "title": re.sub(r"^\[M3\]\[[^\]]+\]\s*", "", issue["title"]),
            "state": issue["state"],
            "assignees": [a["login"] for a in issue["assignees"]],
            "parent": parent_of(issue["body"]),
            "mergedPrs": sorted(pr["number"] for pr in linked if pr["mergedAt"]),
            "openPrs": sorted(pr["number"] for pr in linked if pr["state"] == "OPEN"),
            "approvals": sorted({r["author"]["login"] for pr in linked if pr["mergedAt"] for r in pr["reviews"] if r["state"] == "APPROVED"}),
        })

    kinds = {"epic": [r for r in rows if r["id"] == "E00"], "features": [r for r in rows if re.fullmatch(r"F0\d", r["id"])],
             "tasks": [r for r in rows if r["id"] not in ("E00",) and not re.fullmatch(r"F0\d", r["id"])]}
    summary = {
        "issues": len(rows), "closed": sum(r["state"] == "CLOSED" for r in rows),
        "epic": len(kinds["epic"]), "features": len(kinds["features"]), "tasks": len(kinds["tasks"]),
        "withoutAssignee": [r["number"] for r in rows if not r["assignees"]],
        "tasksWithoutParent": [r["number"] for r in kinds["tasks"] if r["parent"] is None],
        "closedWithoutMergedPr": [r["number"] for r in kinds["tasks"] if r["state"] == "CLOSED" and not r["mergedPrs"]],
        "openWithMergedPr": [r["number"] for r in kinds["tasks"] if r["state"] == "OPEN" and r["mergedPrs"]],
    }
    with open(EXPORT, "w", encoding="utf-8", newline="\n") as handle:
        json.dump({"repository": REPO, "milestone": MILESTONE, "summary": summary, "issues": rows}, handle, indent=2, ensure_ascii=False)
        handle.write("\n")

    def links(values):
        return ", ".join(f"#{v}" for v in values) or "—"

    lines = [BEGIN, "", f"Generated by `scripts/traceability/build-traceability.py` from live GitHub data. Export: [`traceability.json`](traceability.json).", "",
             f"**{summary['issues']} issues** ({summary['epic']} epic, {summary['features']} features, {summary['tasks']} tasks); **{summary['closed']} closed**.", "",
             "| Check | Issues |", "|---|---|",
             f"| Without an assignee | {links(summary['withoutAssignee'])} |",
             f"| Task without a parent feature | {links(summary['tasksWithoutParent'])} |",
             f"| Task closed without a merged PR | {links(summary['closedWithoutMergedPr'])} |",
             f"| Task still open although a PR merged (needs acceptance or human gate) | {links(summary['openWithMergedPr'])} |", "",
             "| # | ID | Title | State | Assignee | Parent | Merged PRs | Open PRs | Approved by |", "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| #{r['number']} | {r['id']} | {r['title']} | {r['state'].lower()} | {', '.join(r['assignees']) or '—'} | "
                     f"{('#' + str(r['parent'])) if r['parent'] else '—'} | {links(r['mergedPrs'])} | {links(r['openPrs'])} | {', '.join(r['approvals']) or '—'} |")
    lines += ["", END]
    generated = "\n".join(lines)

    with open(DOC, encoding="utf-8") as handle:
        document = handle.read()
    if BEGIN not in document or END not in document:
        sys.exit(f"{DOC} has no generated-section markers.")
    document = document[:document.index(BEGIN)] + generated + document[document.index(END) + len(END):]
    with open(DOC, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(document)
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
